import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runTargetBuild, spawnAsync } from '../targets.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));

const fableBin =
  [
    path.join(os.homedir(), '.dotnet/tools/fable'),
    path.join(os.homedir(), '.dotnet/tools/fable.exe'),
  ].find(p => fs.existsSync(p)) ?? 'fable';

const ENV = { ...process.env, MSBUILDDISABLENODEREUSE: '1', DOTNET_CLI_USE_MSBUILD_SERVER: '0' };

// Fable type-checks every binding a project references, the DOM's 2.9 MB
// included, each time it builds one. From this many demos on, they are built
// as one project (`All.fsproj`, compiled to `_all/`), so each is checked once.
// FSHARP_ONE_PROJECT=0 builds each demo alone, however many there are.
const ONE_PROJECT_FROM = 4;
const ALL_OUT = '_all';

function fableArgs(project, outDir, extra = []) {
  const args = [project, '-o', outDir, '--extension', '.mjs', ...extra];
  if (process.env.FABLE_NO_CACHE === '1') args.push('--noCache');
  return args;
}

function restored(dir, project) {
  const assets = path.join(dir, 'obj/project.assets.json');
  return fs.existsSync(assets) && fs.statSync(assets).mtimeMs >= fs.statSync(path.join(dir, project)).mtimeMs;
}

// A restore writes into the bindings the demos share, so the demos are
// restored one at a time, and then built in parallel without one.
async function restoreDemos(toBuild, bindingsDir) {
  for (const { demoDir, specs } of toBuild) {
    const bindings = ['Dom', ...specs.map(s => s.outDir)];
    if (restored(demoDir, 'App.fsproj') && bindings.every(b => restored(path.join(bindingsDir, b), `${b}.fsproj`))) continue;
    await spawnAsync('dotnet', ['restore', 'App.fsproj'], { cwd: demoDir, buffered: true, env: ENV });
  }
}

async function buildTogether(toBuild, bindingsDir) {
  const bindings = new Set(['Dom', ...toBuild.flatMap(({ specs }) => specs.map(s => s.outDir))]);
  const refs = [...bindings].sort().map(b => path.relative(ROOT, path.join(bindingsDir, b, `${b}.fsproj`)));
  const files = toBuild.map(({ demoDir }) => path.relative(ROOT, path.join(demoDir, 'Program.fs')));
  fs.writeFileSync(
    path.join(ROOT, 'All.fsproj'),
    `<!-- Generated by build.mjs: the demos being built, as one project. -->
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <EnableDefaultItems>false</EnableDefaultItems>
  </PropertyGroup>
  <ItemGroup>
${refs.map(r => `    <ProjectReference Include="${r}" />`).join('\n')}
  </ItemGroup>
  <ItemGroup>
${files.map(f => `    <Compile Include="${f}" />`).join('\n')}
  </ItemGroup>
</Project>
`,
  );
  console.log(`Building fsharp: ${toBuild.length} demos as one project...`);
  await spawnAsync(fableBin, fableArgs('All.fsproj', ALL_OUT), { cwd: ROOT, env: ENV });
  // Each demo's page and runner load `js/Program.mjs`.
  for (const { demoDir } of toBuild) {
    const js = path.join(demoDir, 'js');
    const compiled = path.join(ROOT, ALL_OUT, path.relative(ROOT, demoDir), 'Program.mjs');
    fs.mkdirSync(js, { recursive: true });
    fs.writeFileSync(path.join(js, 'Program.mjs'), `import '${path.relative(js, compiled).split(path.sep).join('/')}';\n`);
  }
}

await runTargetBuild({
  targetId: 'fsharp',
  root: ROOT,
  domDirName: 'Dom',
  domSentinel: 'Dom.fsproj',
  pkgSentinel: spec => `${spec.outDir}.fsproj`,
  extraFiles: ['App.fsproj'],
  bindingExt: '.fs',
  beforeDemos: async ({ toBuild, bindingsDir }) => {
    if (toBuild.length >= ONE_PROJECT_FROM && process.env.FSHARP_ONE_PROJECT !== '0') {
      await buildTogether(toBuild, bindingsDir);
      return true;
    }
    await restoreDemos(toBuild, bindingsDir);
  },
  buildDemo: ({ demoDir, buffered }) =>
    spawnAsync(fableBin, fableArgs('App.fsproj', 'js', ['--noRestore']), { cwd: demoDir, buffered, env: ENV }),
});
